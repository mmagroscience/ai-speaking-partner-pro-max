    final w = word.toLowerCase();
    final direct = _extraDirect[w] ?? _direct[w];
    if (direct != null) return direct;

    for (final (keywords, emoji) in _categoryList) {
      if (keywords.any(
        (keyword) =>
            w == keyword || (keyword.length >= 4 && w.startsWith(keyword)),
      )) {
        return emoji;
      }
    }

    final t = type.toLowerCase();
    if (t.contains('verb')) return '⚡';
    if (t.contains('adjective')) return '✨';
    if (t.contains('adverb')) return '💫';
    if (t.contains('number')) return '🔢';
    if (t.contains('preposition') || t.contains('conjunction')) return '🔗';

/// One meaning of a word, with its example sentence when Oxford provides one.
class FlashSense {
  const FlashSense({required this.definition, this.example = ''});

  final String definition;
  final String example;
}

class Flashcard {
  const Flashcard({
    required this.word,
    required this.type,
    required this.cefr,
    required this.phonetic,
    required this.senses,
    this.bangla = '',
    this.emoji = '',
    this.synonyms = const [],
    this.antonyms = const [],
    this.phrases = const [],
    this.babySentence = '',
  });

  final String word;
  final String type;
  final String cefr;
  final String phonetic;
  final List<FlashSense> senses;
  final String bangla;
  final String emoji;
  final List<String> synonyms;
  final List<String> antonyms;
  final List<String> phrases;
  final String babySentence;

  bool get isBaby => bangla.isNotEmpty && senses.isEmpty;
  String get ipa => phonetic.trim().isEmpty ? '' : '/${phonetic.trim()}/';
  String get levelLabel => cefr.toUpperCase();
  String get key => word.toLowerCase();

  String get definition => senses.isEmpty ? '' : senses.first.definition;

  String get firstExample => senses.isEmpty ? '' : senses.first.example;

  List<String> get examples => senses
      .map((sense) => sense.example.trim())
      .where((example) => example.isNotEmpty)
      .toList();

  String get illustration =>
      emoji.isNotEmpty ? emoji : FlashcardEmoji.forWord(word, type);

  String speechText() {
    if (isBaby) return '$word. $babySentence';
    return word;
  }
}

